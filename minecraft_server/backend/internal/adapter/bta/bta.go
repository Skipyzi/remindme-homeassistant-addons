// ------------------------------------------------------------ log grammar ----

// BTA logs through log4j with the pattern [HH:mm:ss] [thread/LEVEL]: message.
var (
	// BTA prints the startup time in nanoseconds, not seconds.
	reReady   = regexp.MustCompile(`Done \(\d+ns\)! For help`)
	reJoin    = regexp.MustCompile(`\]:\s*([A-Za-z0-9_]{1,16}) joined the game\.`)
	reLeave   = regexp.MustCompile(`\]:\s*([A-Za-z0-9_]{1,16}) left the game\.`)
	reVersion = regexp.MustCompile(`Starting Better than Adventure! server for version (\S+)`)
	reLevel   = regexp.MustCompile(`Preparing level "([^"]*)"`)
)

// Parse recognises the console lines the controller acts on.
func (b *Backend) Parse(line string) adapter.LogEvent {
	ev := adapter.LogEvent{Kind: adapter.KindOther, Message: line}

	switch {
	case reReady.MatchString(line):
		ev.Kind = adapter.KindReady
		return ev
	case strings.Contains(line, "Stopping the server"):
		ev.Kind = adapter.KindStopping
		return ev
	case strings.Contains(line, "FAILED TO BIND TO PORT"):
		ev.Kind = adapter.KindPortUnavailable
		return ev
	case strings.Contains(line, "java.lang.OutOfMemoryError"), strings.Contains(line, "NOT ENOUGH RAM"):
		ev.Kind = adapter.KindOutOfMemory
		return ev
	case strings.Contains(line, "Saving complete"):
		ev.Kind = adapter.KindSaved
		return ev
	case strings.Contains(line, "Disabling auto saving"):
		ev.Kind = adapter.KindSaveDisabled
		return ev
	case strings.Contains(line, "Enabling auto saving"):
		ev.Kind = adapter.KindSaveEnabled
		return ev
	case strings.Contains(line, "Failed to load level"), strings.Contains(line, "level.dat is corrupt"),
		strings.Contains(line, "Exception instancing ISaveFormat"):
		ev.Kind = adapter.KindWorldCorrupt
		return ev
	}
	if m := reJoin.FindStringSubmatch(line); m != nil {
		ev.Kind, ev.Player = adapter.KindPlayerJoin, m[1]
		return ev
	}
	if m := reLeave.FindStringSubmatch(line); m != nil {
		ev.Kind, ev.Player = adapter.KindPlayerLeave, m[1]
		return ev
	}
	if m := reVersion.FindStringSubmatch(line); m != nil {
		ev.Kind, ev.Version = adapter.KindVersion, m[1]
		return ev
	}
	if m := reLevel.FindStringSubmatch(line); m != nil {
		ev.Kind, ev.World = adapter.KindOther, m[1]
		return ev
	}
	return ev
}

// PortProperty is the server.properties key BTA reads its listen port from. The
// controller writes it because there is no launch argument for it.
const PortProperty = "server-port"

// FormatPort renders a port for the properties file.
func FormatPort(port int) string { return strconv.Itoa(port) }
