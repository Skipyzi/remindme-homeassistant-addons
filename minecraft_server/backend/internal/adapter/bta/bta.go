// Package bta implements the Better than Adventure! backend.
//
// BTA is a standalone fork of Minecraft Beta 1.7.3. It is not a Bukkit server:
// there are no plugins, no Chunky and no eula.txt, and it takes no launch
// arguments at all - everything it knows comes from server.properties in its
// working directory. The capabilities it reports say so, and the controller
// hides the features that cannot work rather than offering them and failing.
package bta

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"

	"github.com/skipyzi/remindme-homeassistant-addons/minecraft_server/backend/internal/adapter"
	"github.com/skipyzi/remindme-homeassistant-addons/minecraft_server/backend/internal/adapter/javaflags"
)

type Backend struct{}

func New() *Backend { return &Backend{} }

func (b *Backend) Name() string        { return "bta" }
func (b *Backend) DisplayName() string { return "Better than Adventure!" }
func (b *Backend) JarName() string     { return "bta.jar" }

// Capabilities. BTA's world set is a single directory: the other dimensions
// live inside it under `dimensions/`, so unlike Paper there is nothing to list
// separately.
func (b *Backend) Capabilities() adapter.Capabilities {
	return adapter.Capabilities{
		BukkitPlugins:     false,
		BridgeTelemetry:   false,
		TerrainGeneration: false,
		EULAFile:          false,
		ServerPortArg:     false,
		WorldBinding:      adapter.BindLevelLink,
		Dimensions:        []string{"world"},
		Notes: []string{
			"BTA is a fork of Minecraft Beta 1.7.3. Its worlds are in the McRegion format and cannot be opened by a modern server, or the other way round.",
			"There are no Bukkit plugins, so TPS and heap telemetry come from the process rather than from inside the server, and terrain pre-generation is not available.",
			"The listen port is written into server.properties because BTA takes no launch arguments.",
		},
	}
}

func (b *Backend) FlagProfile(profile string, heapMB int) ([]string, error) {
	return javaflags.FlagProfile(profile, heapMB)
}

// Argv builds the JVM command line.
//
// BTA's main method ignores its arguments, so the port and the world are not
// passed here; they are properties. The heap flags are still generated by the
// controller so the limit shown in the UI is the limit in effect.
func (b *Backend) Argv(ctx adapter.LaunchContext) ([]string, error) {
	if ctx.JavaBin == "" {
		return nil, fmt.Errorf("java binary not configured")
	}
	if ctx.JarPath == "" {
		return nil, fmt.Errorf("server JAR not installed")
	}
	if ctx.HeapMaxMB < ctx.HeapMinMB || ctx.HeapMinMB <= 0 {
		return nil, fmt.Errorf("invalid heap configuration %d-%d MB", ctx.HeapMinMB, ctx.HeapMaxMB)
	}
	argv := []string{ctx.JavaBin,
		fmt.Sprintf("-Xms%dM", ctx.HeapMinMB),
		fmt.Sprintf("-Xmx%dM", ctx.HeapMaxMB),
		"-Dfile.encoding=UTF-8",
		"-Djava.awt.headless=true",
	}
	argv = append(argv, ctx.Flags...)
	argv = append(argv, "-jar", ctx.JarPath)
	return argv, nil
}

// WorldArgs is nil: BTA opens the level named by the level-name property inside
// its working directory, so the controller links the active world set there
// instead (adapter.BindLevelLink).
func (b *Backend) WorldArgs(string) []string { return nil }

// Console commands. BTA's console uses Brigadier, so save is one command with
// sub-commands rather than the three hyphenated ones a modern server has.
func (b *Backend) StopCommand() string    { return "stop" }
func (b *Backend) SaveAllCommand() string { return "save all" }
func (b *Backend) SaveOffCommand() string { return "save off" }
func (b *Backend) SaveOnCommand() string  { return "save on" }

// GenerationCommands is empty: no pre-generation plugin exists for BTA.
func (b *Backend) GenerationCommands(adapter.GenerationAction) []string { return nil }

func (b *Backend) PropertiesFile() string { return "server.properties" }

