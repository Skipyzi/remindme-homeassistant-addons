// Argv builds the JVM command line.
//
// Order matters: JVM options first, then -jar, then Paper's own arguments. The
// heap flags are always generated by the controller (custom flags that try to set
// -Xmx are rejected in appcfg.ValidateJavaFlags) so the memory limit shown in the
// UI is always the memory limit in effect.
func (b *Backend) Argv(ctx adapter.LaunchContext) ([]string, error) {
	if ctx.JavaBin == "" {
		return nil, fmt.Errorf("java binary not configured")
	}
	if ctx.JarPath == "" {
		return nil, fmt.Errorf("server JAR not installed")
	}
	if ctx.HeapMaxMB < ctx.HeapMinMB || ctx.HeapMinMB <= 0 {
		return nil, fmt.Errorf("invalid heap configuration %d-%d MB", ctx.HeapMinMB, ctx.HeapMaxMB)
	}
	argv := []string{ctx.JavaBin}
	argv = append(argv,
		fmt.Sprintf("-Xms%dM", ctx.HeapMinMB),
		fmt.Sprintf("-Xmx%dM", ctx.HeapMaxMB),
		"-Dfile.encoding=UTF-8",
		"-Djava.awt.headless=true",
		// Terminal handling: Paper's JLine console fights with a piped stdin.
		"-Dcom.mojang.eula.agree=false",
		"-Dterminal.jline=false",
		"-Dterminal.ansi=false",
	)
	argv = append(argv, ctx.Flags...)
	argv = append(argv, "-jar", ctx.JarPath)
	if ctx.Nogui {
		argv = append(argv, "--nogui")
	}
	if ctx.ServerPort > 0 {
		argv = append(argv, "--port", strconv.Itoa(ctx.ServerPort))
	}
	return argv, nil
}

// WorldArgs returns the Paper arguments that point the server at a world set.
// Switching worlds is therefore a change of launch arguments - no data is moved
// and nothing has to be swapped while the server is stopped.
func (b *Backend) WorldArgs(dir string) []string { return WorldContainerArgs(dir) }

// WorldContainerArgs is the package-level form, kept because it reads better at
// the call sites that build launch arguments.
func WorldContainerArgs(dir string) []string {
	return []string{"--world-container", filepath.ToSlash(dir)}
}

