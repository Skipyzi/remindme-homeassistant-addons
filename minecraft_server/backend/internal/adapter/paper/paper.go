// ------------------------------------------------------------ log grammar ----

var (
	reReady      = regexp.MustCompile(`Done \(([0-9.]+)s\)! For help`)
	reJoin       = regexp.MustCompile(`\]:\s*([A-Za-z0-9_]{1,16}) joined the game`)
	reLeave      = regexp.MustCompile(`\]:\s*([A-Za-z0-9_]{1,16}) left the game`)
	reVersion    = regexp.MustCompile(`Starting minecraft server version ([0-9][^\s]*)`)
	rePaperVer   = regexp.MustCompile(`This server is running ([A-Za-z]+) version ([^\s]+)`)
	rePercent    = regexp.MustCompile(`([0-9]+(?:\.[0-9]+)?)%`)
	reFraction   = regexp.MustCompile(`([0-9]+)\s*/\s*([0-9]+)\s*chunks`)
	reRate       = regexp.MustCompile(`([0-9]+(?:\.[0-9]+)?)\s*(?:cps|chunks/s)`)
	reETA        = regexp.MustCompile(`ETA[:\s]+([0-9]+:[0-9]{2}(?::[0-9]{2})?)`)
	reChunkyName = regexp.MustCompile(`\[Chunky\]\s*(?:\[([^\]]+)\])?`)
)

// Parse recognises the console lines the controller acts on. Anything else is
// KindOther and only ends up in the console history.
func (b *Backend) Parse(line string) adapter.LogEvent {
	ev := adapter.LogEvent{Kind: adapter.KindOther, Message: line}

	if strings.Contains(line, "[Chunky]") || strings.Contains(line, "Chunky") && strings.Contains(line, "Task") {
		return parseChunky(line)
	}

	switch {
	case reReady.MatchString(line):
		ev.Kind = adapter.KindReady
		return ev
	case strings.Contains(line, "Stopping the server"), strings.Contains(line, "Stopping server"):
		ev.Kind = adapter.KindStopping
		return ev
	case strings.Contains(line, "You need to agree to the EULA"):
		ev.Kind = adapter.KindEULARequired
		return ev
	case strings.Contains(line, "FAILED TO BIND TO PORT"):
		ev.Kind = adapter.KindPortUnavailable
		return ev
	case strings.Contains(line, "java.lang.OutOfMemoryError"):
		ev.Kind = adapter.KindOutOfMemory
		return ev
	case strings.Contains(line, "Saved the game"), strings.Contains(line, "Saved the world"):
		ev.Kind = adapter.KindSaved
		return ev
	case strings.Contains(line, "Automatic saving is now disabled"), strings.Contains(line, "Turned off world auto-saving"):
		ev.Kind = adapter.KindSaveDisabled
		return ev
	case strings.Contains(line, "Automatic saving is now enabled"), strings.Contains(line, "Turned on world auto-saving"):
		ev.Kind = adapter.KindSaveEnabled
		return ev
	case strings.Contains(line, "Unknown command") && strings.Contains(strings.ToLower(line), "chunky"):
		ev.Kind = adapter.KindGenNotInstalled
		return ev
	case strings.Contains(line, "Could not load 'plugins"), strings.Contains(line, "Unsupported API version"),
		strings.Contains(line, "was compiled against an incompatible"):
		ev.Kind = adapter.KindPluginIncompat
		return ev
	case strings.Contains(line, "Chunk file at"), strings.Contains(line, "level.dat is corrupt"),
		strings.Contains(line, "Failed to load level"):
		ev.Kind = adapter.KindWorldCorrupt
		return ev
	}
	if m := reJoin.FindStringSubmatch(line); m != nil {
		ev.Kind, ev.Player = adapter.KindPlayerJoin, m[1]
		return ev
	}
	if m := reLeave.FindStringSubmatch(line); m != nil {
		ev.Kind, ev.Player = adapter.KindPlayerLeave, m[1]
		return ev
	}
	if m := reVersion.FindStringSubmatch(line); m != nil {
		ev.Kind, ev.Version = adapter.KindVersion, m[1]
		return ev
	}
	if m := rePaperVer.FindStringSubmatch(line); m != nil {
		ev.Kind, ev.Build = adapter.KindVersion, m[2]
		return ev
	}
	return ev
}

// parseChunky is intentionally tolerant: Chunky's progress format has changed
// between releases, so the parser looks for the individual numbers rather than
// matching one exact sentence.
func parseChunky(line string) adapter.LogEvent {
	ev := adapter.LogEvent{Kind: adapter.KindGenProgress, Message: line}
	if m := reChunkyName.FindStringSubmatch(line); len(m) > 1 {
		ev.World = m[1]
	}
	lower := strings.ToLower(line)
	switch {
	case strings.Contains(lower, "task finished"), strings.Contains(lower, "task complete"),
		strings.Contains(lower, "finished for"), strings.Contains(lower, "100.00%"):
		ev.Kind = adapter.KindGenTaskDone
	case strings.Contains(lower, "task cancelled"), strings.Contains(lower, "task canceled"),
		strings.Contains(lower, "task stopped"):
		ev.Kind = adapter.KindGenTaskCancelled
	case strings.Contains(lower, "task started"), strings.Contains(lower, "starting task"):
		ev.Kind = adapter.KindGenTaskStarted
	}
	if m := rePercent.FindStringSubmatch(line); m != nil {
		ev.Percent, _ = strconv.ParseFloat(m[1], 64)
	}
	if m := reFraction.FindStringSubmatch(line); m != nil {
		ev.ChunksDone, _ = strconv.ParseInt(m[1], 10, 64)
		ev.ChunksTotal, _ = strconv.ParseInt(m[2], 10, 64)
	}
	if m := reRate.FindStringSubmatch(line); m != nil {
		ev.Rate, _ = strconv.ParseFloat(m[1], 64)
	}
	if m := reETA.FindStringSubmatch(line); m != nil {
		ev.ETASeconds = parseClockDuration(m[1])
	}
	return ev
}

func parseClockDuration(v string) int64 {
	parts := strings.Split(v, ":")
	var total int64
	for _, p := range parts {
		n, err := strconv.ParseInt(p, 10, 64)
		if err != nil {
			return 0
		}
		total = total*60 + n
	}
	return total
}
