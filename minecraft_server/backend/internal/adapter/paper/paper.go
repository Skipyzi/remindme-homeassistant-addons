// GenerationCommands maps a generation verb onto Chunky console commands.
func (b *Backend) GenerationCommands(a adapter.GenerationAction) []string {
	switch a.Verb {
	case "configure":
		cmds := []string{}
		if a.World != "" {
			cmds = append(cmds, "chunky world "+a.World)
		}
		cmds = append(cmds,
			fmt.Sprintf("chunky center %d %d", a.CenterX, a.CenterZ),
			"chunky shape "+shapeOrDefault(a.Shape),
			fmt.Sprintf("chunky radius %d", a.Radius),
		)
		return cmds
	case "start":
		return []string{"chunky start"}
	case "pause":
		return []string{"chunky pause"}
	case "resume":
		return []string{"chunky continue"}
	case "cancel":
		return []string{"chunky cancel"}
	case "progress":
		return []string{"chunky progress"}
	case "quiet":
		// Chunky's quiet interval controls how often progress is printed; the
		// controller parses those lines, so a short interval is wanted.
		return []string{"chunky quiet 5"}
	default:
		return nil
	}
}

func shapeOrDefault(s string) string {
	switch s {
	case "square", "circle", "rectangle", "oval", "star", "triangle", "diamond", "pentagon", "hexagon":
		return s
	default:
		return "square"
	}
}

